function write_revision_audit_tables(mode)
%WRITE_REVISION_AUDIT_TABLES Generate manuscript tables from audited MAT data.
    if nargin<1, mode='repaired'; end
    root=helm_output_path('outputs','revision_audit_20260905_repaired');
    if strcmp(mode,'revision20260907'), root=helm_output_path('outputs','revision_20260907','audit'); end
    s=load(fullfile(root,'audit.mat'),'audit'); a=s.audit;
    project=fileparts(fileparts(mfilename('fullpath')));
    path=fullfile(project,'LaTeX_DL_468198_240419','revision_audit_tables.tex');
    f=fopen(path,'w'); assert(f>0); cleanup=onCleanup(@() fclose(f));
    fprintf(f,'%% Generated by write_revision_audit_tables from the verified evidence.\n');
    fprintf(f,['\\begin{table}[t]\n\\centering\\small\n' ...
        '\\caption{Same-snapshot compression audit. Each pair uses identical layer snapshots and identical aggregate tail budgets; entries are summed over three layers. This is a representation-only comparison, not a retrained online solver.}\\label{tab:same-snapshot-audit}\n' ...
        '\\begin{tabular}{llrrr}\\toprule\nProblem & Snapshot trajectory & Global entries & Greedy entries & Saving \\\\\n\\midrule\n']);
    for problem=["halfspace","ecc","pc"]
        for method=["Global","DD"]
            t=a.compression(a.compression.problem==problem & a.compression.snapshot_trajectory==method,:);
            g=sum(t.global_entries); d=sum(t.greedy_entries);
            fprintf(f,'%s & %s & %d & %d & %.1f\\%% \\\\\n',label(problem),method,g,d,100*(1-d/g));
        end
    end
    fprintf(f,'\\bottomrule\\end{tabular}\\end{table}\n');
    fprintf(f,['\\begin{table}[t]\n\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}\n' ...
        '\\caption{Verified two-dimensional training audit. Reduced condition numbers are maxima over all layers and original test parameters. Subdiagonals and snapshot solve residuals range over training samples and subsequent layers. These are training solve errors, not the online reduced-action defects in Table~\\ref{tab:jsc-action}.}\\label{tab:stability-audit}\n' ...
        '\\begin{tabular}{llrrrr}\\toprule\nProblem & Method & $\\max\\kappa_2(B_j)$ & $\\min |h_{j,j-1}|$ & Snapshot residual & Max. snapshot error \\\\\n\\midrule\n']);
    for problem=["halfspace","ecc","pc"]
        for method=["Global","DD"]
            t=a.stability(a.stability.problem==problem & a.stability.method==method,:);
            fprintf(f,'%s & %s & %.2e & %.2e & %.2e & %.2e \\\\\n', ...
                label(problem),method,max(t.max_reduced_condition),min(t.min_hsub,[],'omitnan'), ...
                max(t.max_snapshot_residual),max(t.max_snapshot_direct_error));
        end
    end
    fprintf(f,'\\bottomrule\\end{tabular}\\end{table}\n');
    fprintf(f,['\\begin{table}[t]\n\\centering\\small\n' ...
        '\\caption{Sparse-direct comparison at the first original test parameter of each two-dimensional family. Direct times include factorization and solution, with seven serial repetitions after one warm-up (mean $\\pm$ sample standard deviation). ROM times are complete online times at the same parameter: five-repetition means for PC and archived single measurements for the other families. Assembly is excluded.}\\label{tab:direct-audit}\n' ...
        '\\begin{tabular}{lrrrr}\\toprule\nProblem & Parameter & Direct (s) & Global (s) & DD (s) \\\\\n\\midrule\n']);
    for k=1:height(a.direct)
        t=a.direct(k,:);
        fprintf(f,'%s & %.5f & $%.4f\\pm%.4f$ & %.4f & %.4f \\\\\n', ...
            label(t.problem),t.parameter,t.mean_direct_s,t.std_direct_s,t.global_online_s,t.dd_online_s);
    end
    fprintf(f,'\\bottomrule\\end{tabular}\\end{table}\n');
    fprintf(f,['\\begin{table}[t]\n\\centering\\small\n' ...
        '\\caption{Measured complete in-memory offline construction for the primary two-dimensional runs, including reference generation, replay, snapshot verification/replacement, POD and reduced-operator construction. Initial grid setup and subsequent MAT serialization are excluded.}\\label{tab:offline-audit}\n' ...
        '\\begin{tabular}{lrr}\\toprule\nProblem & Global (s) & DD (s) \\\\\n\\midrule\n']);
    for problem=["halfspace","ecc","pc"]
        t=a.offline(a.offline.problem==problem,:);
        fprintf(f,'%s & %.3f & %.3f \\\\\n',label(problem), ...
            t.total_offline_s(t.method=="Global"),t.total_offline_s(t.method=="DD"));
    end
    fprintf(f,'\\bottomrule\\end{tabular}\\end{table}\n');
    fprintf(f,['\\begin{table}[t]\n\\centering\\scriptsize\\setlength{\\tabcolsep}{4pt}\n' ...
        '\\caption{Frozen waveguide queries (I: interpolation, E: extrapolation), selected after fixing the archived model, without retraining or rank changes. Times include the same setup convention as Table~\\ref{tab:3d-online}. The last column is the maximum true residual across the three solvers.}\\label{tab:frozen-holdout}\n' ...
        '\\begin{tabular}{lrlrrrrr}\\toprule\nProblem & $\\mu$ & Set & MG (s) & Global (s) & DD (s) & DD speedup & Max. residual \\\\\n\\midrule\n']);
    names={'lens','waveguide'}; if strcmp(mode,'revision20260907'), names={'waveguide'}; end
    for name=names
        spec=helmholtz_3d_40pct_config(name{1});
        file=helm_output_path('outputs','helmholtz_3d_candidates','large', ...
            ['helmholtz_3d_candidates_' name{1} '_frozen_holdout_20260905.csv']);
        t=readtable(file,'TextType','string'); t=t(t.method~="direct",:);
        assert(all(t.flag==0) && all(t.final_relres<=1e-6));
        for mu=unique(t.mu)'
            rows=t(t.mu==mu,:); lo=spec.problem_cfg.parameter_range(1); hi=spec.problem_cfg.parameter_range(2);
            setname='I'; if mu<lo || mu>hi, setname='E'; end
            mg=rows.total_s(rows.method=="shifted");
            g=rows.total_s(rows.method=="global"); dd=rows.total_s(rows.method=="dd");
            fprintf(f,'%s & %.5f & %s & %.3f & %.3f & %.3f & %.2f & %.2e \\\\\n', ...
                name{1},mu,setname,mg,g,dd,mg/dd,max(rows.final_relres));
        end
    end
    fprintf(f,'\\bottomrule\\end{tabular}\\end{table}\n');
end

function value=label(problem)
    switch problem
        case "halfspace", value='Half-space';
        case "ecc", value='Elliptic obstacle';
        case "pc", value='Photonic crystal';
    end
end
