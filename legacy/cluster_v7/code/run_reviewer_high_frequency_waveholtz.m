function summary=run_reviewer_high_frequency_waveholtz(mode)
%RUN_REVIEWER_HIGH_FREQUENCY_WAVEHOLTZ Active Helm/WaveHoltz workflow stress test.
% Fixed PPW, 24 training speeds, three fixed interpolation queries at omega
% 53.5, 107, 214. Uses the active reference/replay/lift/completion implementation.
% Each frequency/method is checkpointed before proceeding to the next case.
    if nargin<1, mode='paper'; end
    assert(ismember(mode,{'paper','smoke'}));
    out=helm_output_path('outputs','reviewer_20260909','high_frequency_waveholtz');
    if ~isfolder(out), mkdir(out); end
    scales=[1,2,4]; tests=[0.8297,0.8761,0.9431]; nt=24;
    if strcmp(mode,'smoke'), scales=0.25; tests=0.8761; nt=6; end
    summary=table();
    for scale=scales
        for method={'global','dd'}
            tag=sprintf('%s_scale%g',method{1},scale); file=fullfile(out,[tag '.mat']);
            if isfile(file)
                d=load(file,'row'); row=d.row;
            else
                cfg=struct('Nphys',round(126*scale)-1,'omega',53.5*scale, ...
                    'sigma_max',80*scale,'train_params',linspace(0.8,0.95,nt), ...
                    'test_params',tests,'reference_mode','helm_lift', ...
                    'corr_basis_style','global','corr_num_layers',3, ...
                    'corr_pod_singular_value_tols',1e-5*[1,1,1], ...
                    'use_direct_rom_init',false,'build_direct_rom_when_unused',false, ...
                    'online_completion_mode','waveholtz','online_wave_solver','gmres', ...
                    'online_helm_accept_tol',1e-8,'online_true_helm_tol',1e-8, ...
                    'wh_tol',1e-10,'wh_gmres_restart',40,'wh_gmres_maxit',20, ...
                    'run_wave_baselines',strcmp(method{1},'global'), ...
                    'run_nr_rom_comparison',false,'helm_baseline_iters',1, ...
                    'parallel_train',false,'parallel_test',false, ...
                    'do_plots',false,'save_plots',false,'save_benchmark',false);
                if strcmp(method{1},'dd'), cfg=halfspace_paper_dd_config(cfg); end
                fprintf('\nWaveHoltz frequency study: %s\n',tag);
                r=helm_waveholtz_correction_rom(cfg);
                storage=rom_deployment_storage(r.correction_rom.layers);
                rows=table();
                for k=1:numel(tests)
                    mu=tests(k); A=r.problem.A_base+(mu^(-2)-1)*r.problem.A_right;
                    rho=norm(r.rhs-A*r.test.online_final_u(:,k))/norm(r.rhs);
                    assert(rho<=1e-8,'ROM+WaveHoltz true residual failed.');
                    baseline_rho=NaN;
                    if strcmp(method{1},'global')
                        baseline_rho=norm(r.rhs-A*r.test.plain_fp_u(:,k))/norm(r.rhs);
                        assert(baseline_rho<=1e-8,'Plain WaveHoltz true residual failed.');
                    end
                    rows=[rows;table(string(method{1}),scale,r.cfg.omega,r.problem.Ntot,mu, ...
                        r.test.online_precorr_relres_final(k),r.test.online_precorr_time(k), ...
                        r.test.online_fp_iter(k),r.test.online_total_time(k),rho, ...
                        r.test.plain_fp_iter(k),r.test.plain_fp_time(k),baseline_rho, ...
                        'VariableNames',{'method','scale','omega','N','parameter','post_ROM_residual', ...
                        'ROM_s','completion_iterations','total_s','true_residual', ...
                        'baseline_iterations','baseline_s','baseline_true_residual'})]; %#ok<AGROW>
                end
                row=table(string(method{1}),scale,r.cfg.omega,r.problem.Ntot, ...
                    string(mat2str(storage.ranks)),storage.basis_MiB,storage.payload_MiB, ...
                    r.timing.offline,mean(rows.total_s),max(rows.true_residual), ...
                    mean(rows.completion_iterations),max(rows.post_ROM_residual), ...
                    'VariableNames',{'method','scale','omega','N','ranks','basis_MiB', ...
                    'payload_MiB','offline_s','online_s','max_true_residual', ...
                    'mean_completion_iterations','max_post_ROM_residual'});
                artifact=struct('cfg',r.cfg,'problem',r.problem,'rhs',r.rhs, ...
                    'layers',{r.correction_rom.layers},'test',r.test,'timing',r.timing);
                % Full WaveHoltz training states are reconstructible from fields;
                % do not duplicate those large auxiliary arrays in this archive.
                save(file,'row','rows','artifact','-v7.3');
                writetable(rows,fullfile(out,[tag '_queries.csv']));
                clear r artifact;
            end
            summary=[summary;row]; %#ok<AGROW>
            writetable(summary,fullfile(out,['summary_' mode '.csv']));
            disp(row);
        end
    end
end
